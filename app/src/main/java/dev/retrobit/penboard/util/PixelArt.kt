    /** Apakah [action] punya ikon pixel art sendiri. */
    fun hasPattern(action: KeyAction): Boolean = PATTERNS.containsKey(action)

    /** Aksi yang sudah punya ikon, urut seperti kanvasnya dipakai. */
    val supported: List<KeyAction> get() = PATTERNS.keys.toList()

    private fun art(vararg rows: String) = Pattern(rows.toList())
